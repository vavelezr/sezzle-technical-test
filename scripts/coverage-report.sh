#!/usr/bin/env bash
# Regenerates docs/coverage.md and the coverage summary in README.md from real
# test runs, so coverage numbers are never written by hand.
#
# It runs the same coverage commands as `make coverage` (thresholds still
# enforced) and fails without touching any file if a run fails.
#
# Usage: make coverage-report   (or ./scripts/coverage-report.sh)
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
report="$root/docs/coverage.md"
readme="$root/README.md"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

run_logged() { # run_logged <log file> <command...>: quiet unless the command fails
  local log="$1"
  shift
  if ! "$@" >"$log" 2>&1; then
    cat "$log" >&2
    echo "coverage-report: '$*' failed; no files were changed" >&2
    exit 1
  fi
}

if ! grep -q '<!-- coverage-summary:start -->' "$readme" || ! grep -q '<!-- coverage-summary:end -->' "$readme"; then
  echo "coverage-report: coverage-summary markers not found in README.md" >&2
  exit 1
fi

echo "==> Backend: make coverage"
# GOFLAGS=-v makes `go test` list every test, so passing tests can be counted.
run_logged "$work/backend.log" env GOFLAGS=-v make --no-print-directory -C "$root/backend" coverage
(cd "$root/backend" && go tool cover -func=coverage.out) >"$work/backend-func.txt"

echo "==> Frontend: npm run test:coverage"
run_logged "$work/frontend.log" env NO_COLOR=1 npm --prefix "$root/frontend" run --silent test:coverage

backend_tests="$(grep -c -- '--- PASS' "$work/backend.log")"
backend_total="$(awk '/^total:/ { print $NF }' "$work/backend-func.txt")"
frontend_tests="$(awk '$1 == "Tests" { print $2 }' "$work/frontend.log")"
frontend_files="$(awk '$1 == "Test" && $2 == "Files" { print $3 }' "$work/frontend.log")"
generated_on="$(date -u +%Y-%m-%d)"

# Summary shared verbatim by README.md and docs/coverage.md.
{
  echo "**Backend**: ${backend_tests} passing tests and subtests, **${backend_total}** total statement coverage of \`internal/\`"
  echo
  echo "| Package | Statements |"
  echo "| ------- | ---------- |"
  sed -nE 's#^ok[[:space:]]+[^[:space:]]+/backend/(internal/[^[:space:]]+).*coverage: ([0-9.]+%).*#| `\1` | \2 |#p' \
    "$work/backend.log"
  echo "| **Total** | **${backend_total}** |"
  echo
  echo "**Frontend**: ${frontend_tests} passing tests in ${frontend_files} files"
  echo
  echo "| Metric | Coverage |"
  echo "| ------ | -------- |"
  sed -nE 's#^(Statements|Branches|Functions|Lines)[[:space:]]*: ([0-9.]+%) \( ([0-9]+/[0-9]+) \)#| \1 | \2 (\3) |#p' \
    "$root/frontend/coverage/text-summary.txt"
} >"$work/summary.md"

mkdir -p "$(dirname "$report")"
{
  cat <<EOF
# Coverage report

<!-- Generated by \`make coverage-report\` (scripts/coverage-report.sh). Do not edit by hand. -->

Generated on **${generated_on}** (UTC) with $(cd "$root/backend" && go version | awk '{ print $3 }') and Node $(node --version).

To reproduce, run from the repository root:

\`\`\`bash
make coverage-report
\`\`\`

which runs:

\`\`\`bash
cd backend && make coverage                     # go test -covermode=atomic -coverprofile=coverage.out ./internal/...
cd backend && go tool cover -func=coverage.out  # per-function report below
cd frontend && npm run test:coverage            # vitest run --coverage (v8)
\`\`\`

Thresholds are enforced by those commands: backend total ≥ 90%, frontend statements, branches,
functions and lines ≥ 85% each. The interactive HTML reports (\`backend/coverage.html\`,
\`frontend/coverage/index.html\`) are generated locally and uploaded as CI artifacts; they are not
committed.

## Summary

EOF
  cat "$work/summary.md"
  cat <<'EOF'

## Backend: `go tool cover -func=coverage.out`

```text
EOF
  cat "$work/backend-func.txt"
  cat <<'EOF'
```

## Frontend: Vitest v8 text report

Files that only declare TypeScript types (for example `calculation.ts` and `commands.ts`) compile
to no JavaScript, so they have 0 of 0 statements and are reported as `0`. They do not affect the
totals.

```text
EOF
  cat "$root/frontend/coverage/coverage.txt"
  echo
  cat "$root/frontend/coverage/text-summary.txt"
  echo '```'
} >"$report"

# Replace the README block between the coverage-summary markers.
awk -v summary="$work/summary.md" '
  /<!-- coverage-summary:start -->/ {
    print
    print "<!-- Generated by `make coverage-report`; do not edit by hand. -->"
    print ""
    while ((getline line < summary) > 0) print line
    print ""
    skipping = 1
    next
  }
  /<!-- coverage-summary:end -->/ { skipping = 0 }
  !skipping { print }
' "$readme" >"$work/README.md"
cp "$work/README.md" "$readme"

echo "==> Wrote ${report#"$root"/} and updated the README coverage summary"
